"""
evals/eval_rag_pipeline.py

End-to-end RAG evaluation.

Pipeline:
    Query
      ↓
    RerankingRetriever
      ↓
    Retrieved Context
      ↓
    Cohere Generator
      ↓
    Generated Answer
      ↓
    Cohere Judge
      ↓
    Contextual Relevancy
    Faithfulness
    Answer Relevancy

Run:
    python -m evals.eval_rag_pipeline
"""


# ============================================================
# PROJECT ROOT
# ============================================================

import sys
from pathlib import Path

sys.path.append(
    str(Path(__file__).resolve().parent.parent)
)


# ============================================================
# IMPORTS
# ============================================================

import json

from dotenv import load_dotenv

from deepeval import evaluate
from deepeval.evaluate import CacheConfig
from deepeval.test_case import LLMTestCase

from deepeval.metrics import (
    FaithfulnessMetric,
    AnswerRelevancyMetric,
    ContextualRelevancyMetric,
)

from src.rag_pipeline import RagPipeline
from src.cohere_judge import CohereJudge


# ============================================================
# LOAD ENVIRONMENT VARIABLES
# ============================================================

load_dotenv()


# ============================================================
# CONFIG
# ============================================================

GOLDEN_PATH = "golden/faithfulness_dataset.json"

THRESHOLD = 0.7


# ============================================================
# COHERE JUDGE
# ============================================================

JUDGE_MODEL = CohereJudge(
    model="command-a-03-2025"
)


# ============================================================
# 1. LOAD GOLDEN SET
# ============================================================

with open(GOLDEN_PATH, encoding="utf-8") as f:
    goldens = json.load(f)

print(
    f"Loaded {len(goldens)} golden test cases."
)


# ============================================================
# 2. BUILD RAG PIPELINE
# ============================================================

rag = RagPipeline(
    fetch_k=10,
    top_k=5,
)


# ============================================================
# 3. RUN RAG PIPELINE
# ============================================================

test_cases = []


for i, g in enumerate(goldens):

    query = g["query"]

    print(
        f"\n[{i + 1}/{len(goldens)}]"
    )

    print(
        f"Query: {query}"
    )

    # --------------------------------------------------------
    # RAG:
    # query → retrieve → rerank → generate
    # --------------------------------------------------------

    result = rag.invoke(query)

    answer = result["answer"]

    context = result["context"]

    print(
        f"Retrieved {len(context)} context chunks."
    )

    print(
        f"Answer: {answer[:150]}..."
    )

    # --------------------------------------------------------
    # Create DeepEval test case
    # --------------------------------------------------------

    test_cases.append(
        LLMTestCase(

            input=query,

            # Actual answer generated by your RAG pipeline
            actual_output=answer,

            # Actual context retrieved by your pipeline
            retrieval_context=context,
        )
    )


# ============================================================
# 4. RAG TRIAD METRICS
# ============================================================

metrics = [

    # --------------------------------------------------------
    # CONTEXTUAL RELEVANCY
    # --------------------------------------------------------
    #
    # Are the retrieved chunks relevant to the question?
    #
    ContextualRelevancyMetric(
        threshold=THRESHOLD,
        model=JUDGE_MODEL,
        include_reason=True,
    ),

    # --------------------------------------------------------
    # FAITHFULNESS
    # --------------------------------------------------------
    #
    # Is the generated answer actually supported
    # by the retrieved context?
    #
    FaithfulnessMetric(
        threshold=THRESHOLD,
        model=JUDGE_MODEL,
        include_reason=True,
    ),

    # --------------------------------------------------------
    # ANSWER RELEVANCY
    # --------------------------------------------------------
    #
    # Does the generated answer actually answer
    # the user's question?
    #
    AnswerRelevancyMetric(
        threshold=THRESHOLD,
        model=JUDGE_MODEL,
        include_reason=True,
    ),
]


# ============================================================
# 5. RUN EVALUATION
# ============================================================

print("\n========================================")
print("Starting RAG Pipeline Evaluation")
print("========================================")
print("Retriever : RerankingRetriever")
print("Generator : Cohere Command A")
print("Judge     : Cohere Command A")
print("========================================\n")


evaluate(

    test_cases=test_cases,

    metrics=metrics,

    # --------------------------------------------------------
    # Disable DeepEval cache because of the Windows
    # portalocker/shared-lock issue.
    # --------------------------------------------------------

    cache_config=CacheConfig(
        write_cache=False,
        use_cache=False,
    ),

    hyperparameters={

        "retriever": "reranked",

        "fetch_k": 10,

        "top_k": 5,

        "embedding_model": "text-embedding-3-small",

        "chunk_size": 1000,

        "chunk_overlap": 150,

        "reranker": "cross-encoder/ms-marco-MiniLM-L-6-v2",

        "generator": "cohere/command-a-03-2025",

        "judge_model": "cohere/command-a-03-2025",

        "golden_set": GOLDEN_PATH,

        "temperature": 0,
    },
)


print("\n========================================")
print("RAG evaluation completed.")
print("========================================")